"""LH047 re-audit, W47: tables from requests-judged.csv (Amendment 1's reporting: every count by request
and by practice, each failing request's status; verdicts on current re-reads counted apart).
Run from the repository root: python3 -I studies/LH047/data/reaudit-2026-W47/code/tabulate.py
Writes tables.md and summary.json beside requests-judged.csv; prints summary.json.
"""
import csv, json, os
from collections import Counter, defaultdict

D = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ALL = list(csv.DictReader(open(os.path.join(D, 'requests-judged.csv'), newline='')))
A = [r for r in ALL if r['counted'] == 'audited']
RULES = ['R1', 'R2', 'R2_agent', 'K8', 'R4', 'R5', 'R5_excl_robots', 'R6', 'R7', 'R8', 'overall_A', 'overall_B', 'overall_K8']


def prov(r):
    p = r['robots_prov']
    if r['kind'] == 'robots':
        return 'robots.txt read (always allowed)'
    if p.startswith('current re-read, bytes identical'):
        return 're-read 23 Nov, identical to the file read then (sha256)'
    if p.startswith('current re-read, bytes differ'):
        return 're-read 23 Nov, differs from the file read then (sha256)'
    if p.startswith('current'):
        return 're-read 23 Nov (file at the time not known)'
    if p in ('', 'none'):
        return 'no robots.txt evidence'
    return 'copy or status from the week'


def status_bucket(s):
    if not s:
        return 'not recorded'
    if s.startswith('2'):
        return '2xx'
    if s.startswith('3'):
        return '3xx'
    if s == '404':
        return '404'
    if s[:1] in '45' and s[:3].isdigit():
        return 'other refusal (%s)' % s
    return 'no answer (%s)' % s[:20]


def fails(v):
    return v.startswith('does not comply')


lines = []


def table(title, head, rows):
    lines.append('\n### %s\n' % title)
    lines.append('| ' + ' | '.join(head) + ' |')
    lines.append('|' + '---|' * len(head))
    for r in rows:
        lines.append('| ' + ' | '.join(str(x) for x in r) + ' |')


lines.append('# LH047 re-audit of ISO week 2026-W47: tables (generated by code/tabulate.py; unreviewed)')
apart = Counter(r['counted'] for r in ALL if r['counted'] != 'audited')
table('Population', ['what', 'rows'], [['audited requests (sent, with a UTC time in the week)', len(A)],
                                        ['of which page or API requests', sum(1 for r in A if r['kind'] == 'page')],
                                        ['of which robots.txt reads logged as rows', sum(1 for r in A if r['kind'] == 'robots' and r['sent'] == 'yes')],
                                        ['of which robots.txt reads counted from code (gate, no logged row)', sum(1 for r in A if r['sent'] == 'implicit robots read')]]
      + [[k, v] for k, v in sorted(apart.items())])
P = sorted({prov(r) for r in A})
table('Verdicts by rule, by request, split by the robots.txt evidence used (re-reads counted apart)',
      ['rule', 'verdict'] + P + ['all'],
      [[rule, v] + [sum(1 for r in A if r[rule] == v and prov(r) == p) for p in P] + [sum(1 for r in A if r[rule] == v)]
       for rule in RULES for v in sorted({r[rule] for r in A})])
# by practice
prac = defaultdict(list)
for r in A:
    prac[r['practice']].append(r)
rows = []
for p, rs in sorted(prac.items()):
    rows.append([p, len(rs)] + ['%d / %d' % (sum(1 for r in rs if fails(r[k])), sum(1 for r in rs if r[k] == 'unknown'))
                                for k in ('R1', 'R2', 'K8', 'R4', 'R5', 'R5_excl_robots', 'R6', 'R8', 'overall_A', 'overall_B', 'overall_K8')])
table('By practice: requests, then "does not comply / unknown" under each rule',
      ['practice', 'requests', 'R1', 'R2', 'K8', 'R4', 'R5', 'R5 excl. robots', 'R6', 'R8', 'overall A', 'overall B', 'overall K8'], rows)
# failing requests by rule and status
rows = []
for k in ('R1', 'R2', 'K8', 'R4', 'R5', 'R5_excl_robots', 'R6', 'R8'):
    for p, rs in sorted(prac.items()):
        f = [r for r in rs if fails(r[k])]
        if f:
            c = Counter(status_bucket(r['status']) for r in f)
            rows.append([k, p, len(f), '; '.join('%s %d' % kv for kv in sorted(c.items())),
                         '; '.join('%s %d' % kv for kv in sorted(Counter(prov(r) for r in f).items()))])
table('Failing requests: rule, practice, count, status received, robots.txt evidence', ['rule', 'practice', 'n', 'status', 'evidence'], rows)
# overall by status
for k in ('overall_A', 'overall_B', 'overall_K8'):
    f = [r for r in A if fails(r[k])]
    table('%s does not comply: status received' % k, ['status', 'n'], sorted(Counter(status_bucket(r['status']) for r in f).items()))
# R2 by token
tok = Counter(t for r in A for t in r['R2_tokens'].split())
table('Reading B by token: requests a group naming the token disallows', ['token', 'requests'], sorted(tok.items()))
table('R3 (context only)', ['R3', 'requests'], sorted(Counter(r['R3'] or 'not evaluated (robots.txt read or no parsed copy)' for r in A).items()))
# R5 detail
rows = []
by = defaultdict(list)
for r in A:
    if r['crawl_delay']:
        by[(r['study'], r['host'])].append(r)
for (s, h), rs in sorted(by.items()):
    rows.append([s, h, rs[0]['crawl_delay'], rs[0]['host_n'], rs[0]['host_max60'], rs[0]['host_min_gap'],
                 sum(1 for r in rs if fails(r['R5'])), sum(1 for r in rs if fails(r['R5_excl_robots'])), sum(1 for r in rs if r['R5'] == 'unknown'),
                 prov(next((r for r in rs if r['kind'] == 'page'), rs[0]))])
table('R5: study and host where the applicable group sets Crawl-delay (requests in the study-host pair counted across the week)',
      ['study', 'host', 'Crawl-delay', 'requests', 'most in 60 s', 'shortest gap (s)', 'R5 fails', 'R5 fails excl. robots', 'R5 unknown', 'evidence'], rows)
table('R6: walls and later requests', ['practice', 'URL', 'why'], [[r['practice'], r['url'][:90], r['R6_why'][:160]] for r in A if fails(r['R6'])])
table('R8 identification classes (Amendment 1)', ['practice', 'R8', 'requests'],
      sorted([(p, v, n) for (p, v), n in Counter((r['practice'], r['R8']) for r in A).items()]))
table('Unknown under R1: why', ['reason', 'requests'], sorted(Counter(r['R1_rule'][:90] for r in A if r['R1'] == 'unknown').items()))
table('Robots.txt evidence used for page requests', ['provenance', 'requests'], sorted(Counter(r['robots_prov'] for r in A if r['kind'] == 'page').items()))
table('Context, not a verdict: the keeper\'s 21 November decision', ['column', 'value', 'requests'],
      [[k, v, n] for k in ('K21_oneoff', 'K21_keep') for v, n in sorted(Counter(r[k] for r in A if r[k]).items())])
table('Gate refusals (not sent; counted apart)', ['practice', 'requests'], sorted(Counter(r['practice'] for r in ALL if r['counted'] == 'apart: refused by the gate').items()))
summ = dict(audited=len(A), apart=dict(apart),
            by_rule={k: dict(Counter(r[k] for r in A)) for k in RULES},
            by_rule_week_evidence_or_robots_reads={k: dict(Counter(r[k] for r in A if not prov(r).startswith('re-read') and prov(r) != 'no robots.txt evidence')) for k in RULES},
            by_rule_on_reread={k: dict(Counter(r[k] for r in A if prov(r).startswith('re-read'))) for k in RULES},
            practices_failing={k: sorted({r['practice'] for r in A if fails(r[k])}) for k in ('overall_A', 'overall_B', 'overall_K8')},
            implicit_robots=sum(1 for r in A if r['sent'] == 'implicit robots read'))
open(os.path.join(D, 'tables.md'), 'w').write('\n'.join(lines) + '\n')
json.dump(summ, open(os.path.join(D, 'summary.json'), 'w'), indent=1, sort_keys=True)
print(json.dumps(summ, indent=1, sort_keys=True))
